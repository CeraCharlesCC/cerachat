import { expect, test, type Locator, type Page } from '@playwright/test'

async function drag(page: Page, handle: Locator, dx: number, dy = 0) {
  const box = (await handle.boundingBox())!
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2)
  await page.mouse.down()
  await page.mouse.move(box.x + box.width / 2 + dx, box.y + box.height / 2 + dy, { steps: 8 })
  await page.mouse.up()
}

test('sidebars resize with the pointer and keyboard, persist, and preserve the chat minimum', async ({ page }) => {
  await page.goto('/')
  const threads = page.getByRole('separator', { name: 'Resize threads panel', exact: true })
  const context = page.getByRole('separator', { name: 'Resize context panel', exact: true })
  await expect(threads).toHaveAttribute('aria-valuenow', '220')
  await drag(page, threads, 80)
  await expect(threads).toHaveAttribute('aria-valuenow', '300')
  await expect(page.locator('#threads-panel')).toHaveCSS('width', '300px')
  await drag(page, context, -100)
  await expect(context).toHaveAttribute('aria-valuenow', '420')
  await page.reload()
  await expect(threads).toHaveAttribute('aria-valuenow', '300')
  await expect(context).toHaveAttribute('aria-valuenow', '420')
  await context.focus()
  await page.keyboard.press('ArrowRight')
  await expect(context).toHaveAttribute('aria-valuenow', '404')
  await page.keyboard.press('Home')
  await expect(context).toHaveAttribute('aria-valuenow', '300')
  await drag(page, threads, -1000)
  await expect(threads).toHaveAttribute('aria-valuenow', '200')
  await drag(page, threads, 1000)
  await expect(threads).toHaveAttribute('aria-valuenow', '400')
  await drag(page, context, -1000)
  await page.setViewportSize({ width: 1101, height: 800 })
  await expect.poll(async () => (await page.getByRole('main').boundingBox())!.width).toBeGreaterThanOrEqual(439.9)
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(1101)
  await page.setViewportSize({ width: 1440, height: 1000 })
  await expect(threads).toHaveAttribute('aria-valuenow', '400')
  await threads.dblclick()
  await expect(threads).toHaveAttribute('aria-valuenow', '220')
})

test('panels collapse and reopen at their saved widths', async ({ page }) => {
  await page.goto('/')
  const main = page.getByRole('main')
  const initial = (await main.boundingBox())!.width
  await page.getByRole('button', { name: 'Toggle threads panel' }).click()
  await expect(page.locator('#threads-panel')).toBeHidden()
  await page.getByRole('button', { name: 'Toggle context panel' }).click()
  await expect(page.locator('#context-panel')).toBeHidden()
  await expect(main).toHaveCSS('width', '1440px')
  await page.getByRole('button', { name: 'Toggle threads panel' }).click()
  await page.getByRole('button', { name: 'Toggle context panel' }).click()
  await expect.poll(async () => (await main.boundingBox())!.width).toBe(initial)
})

test('composer and source library resize vertically, keep usable minimums and restore after reload', async ({ page }) => {
  await page.goto('/')
  const composer = page.getByRole('separator', { name: 'Resize message composer' })
  const library = page.getByRole('separator', { name: 'Resize source library' })
  await drag(page, composer, 0, -100)
  await expect(composer).toHaveAttribute('aria-valuenow', '324')
  await expect(page.getByRole('region', { name: 'Message composer' })).toHaveCSS('height', '324px')
  await drag(page, library, 0, -80)
  await expect(library).toHaveAttribute('aria-valuenow', '144')
  await page.reload()
  await expect(composer).toHaveAttribute('aria-valuenow', '324')
  await expect(library).toHaveAttribute('aria-valuenow', '144')
  await composer.focus()
  await page.keyboard.press('Home')
  await expect(composer).toHaveAttribute('aria-valuenow', '200')
  expect((await page.getByLabel('Message input').boundingBox())!.height).toBeGreaterThanOrEqual(40)
  await page.keyboard.press('Enter')
  await expect(composer).toHaveAttribute('aria-valuenow', '224')
  await library.dblclick()
  await expect(library).toHaveAttribute('aria-valuenow', '224')
})

test('compact layouts keep panels inside the viewport and restore desktop resizing', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  await page.getByRole('button', { name: 'Context', exact: true }).click()
  const panel = page.locator('#context-panel')
  await expect(panel).toBeVisible()
  await expect.poll(async () => Math.round((await panel.boundingBox())!.x)).toBe(31)
  const box = (await panel.boundingBox())!
  expect(box.x + box.width).toBeLessThanOrEqual(390)
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(390)
  await page.getByRole('button', { name: 'Close side panel' }).click({ position: { x: 10, y: 400 } })
  await expect(panel).toBeHidden()
  await page.setViewportSize({ width: 1440, height: 1000 })
  await expect(page.getByRole('separator', { name: 'Resize context panel', exact: true })).toBeVisible()
  await expect(page.getByRole('separator', { name: 'Resize threads panel', exact: true })).toBeVisible()
})
